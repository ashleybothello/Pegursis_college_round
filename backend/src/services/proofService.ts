import fs from 'fs';
// @ts-ignore - snarkjs does not have official ts declarations
import * as snarkjs from 'snarkjs';
import {
  CreditScoringInputs,
  ProofGenerationResult,
  ProofService,
  SolidityProof,
} from '../types/index.js';
import { calculateCreditScore, CREDIT_MODEL_VERSION } from './creditScoring.js';
// The circuit-aware real service (Person 1+2 artifacts). Imported here so the
// App's 'real' factory can return it without circular-dependency issues.
import { ZkCreditProofService } from './zkProofService.js';

export interface ProofServiceConfig {
  circuitWasmPath?: string;
  circuitZkeyPath?: string;
  verificationKeyPath?: string;
  publicSignalOrder?: 'SCORE_FIRST' | 'VERSION_FIRST';
}

/**
 * Transforms snarkjs Groth16 proof into the exact uint256 coordinate structure
 * expected by standard Solidity Verifiers (e.g., generated by snarkjs zkey export solidityverifier).
 * Notice: in Ethereum BN254 ecPairing, G2 points in pi_b have reversed coordinate order [x_im, x_re].
 */
export function formatSnarkjsProofForSolidity(
  rawProof: {
    pi_a: string[];
    pi_b: string[][];
    pi_c: string[];
  },
  publicSignals: string[]
): SolidityProof {
  return {
    a: [rawProof.pi_a[0], rawProof.pi_a[1]],
    b: [
      [rawProof.pi_b[0][1], rawProof.pi_b[0][0]],
      [rawProof.pi_b[1][1], rawProof.pi_b[1][0]],
    ],
    c: [rawProof.pi_c[0], rawProof.pi_c[1]],
    publicSignals: [...publicSignals],
  };
}

/**
 * MockProofService
 * Used for local testing, rapid iteration, and development environments where
 * heavy snarkjs trusted setup ceremonies or Circom compilations are not yet executed.
 */
export class MockProofService implements ProofService {
  private publicSignalOrder: 'SCORE_FIRST' | 'VERSION_FIRST';

  constructor(options?: { publicSignalOrder?: 'SCORE_FIRST' | 'VERSION_FIRST' }) {
    this.publicSignalOrder = options?.publicSignalOrder ?? 'SCORE_FIRST';
  }

  async generateProof(inputs: CreditScoringInputs): Promise<ProofGenerationResult> {
    const calc = calculateCreditScore(inputs);

    const publicSignals =
      this.publicSignalOrder === 'SCORE_FIRST'
        ? [calc.score.toString(), calc.modelVersion.toString()]
        : [calc.modelVersion.toString(), calc.score.toString()];

    // Deterministic mock proof coordinates formatted as uint256 decimal strings
    const mockSolidityProof: SolidityProof = {
      a: [
        '0x1234567890abcdef1234567890abcdef1234567890abcdef1234567890abcdef',
        '0xabcdef1234567890abcdef1234567890abcdef1234567890abcdef1234567890',
      ],
      b: [
        [
          '0x1111111111111111111111111111111111111111111111111111111111111111',
          '0x2222222222222222222222222222222222222222222222222222222222222222',
        ],
        [
          '0x3333333333333333333333333333333333333333333333333333333333333333',
          '0x4444444444444444444444444444444444444444444444444444444444444444',
        ],
      ],
      c: [
        '0x5555555555555555555555555555555555555555555555555555555555555555',
        '0x6666666666666666666666666666666666666666666666666666666666666666',
      ],
      publicSignals,
    };

    return {
      proof: mockSolidityProof,
      publicSignals,
      score: calc.score,
      modelVersion: calc.modelVersion,
      isMock: true,
      generatedAt: new Date().toISOString(),
    };
  }

  async verifyProof(proof: SolidityProof, publicSignals: string[]): Promise<boolean> {
    if (!proof || !proof.a || !proof.b || !proof.c || !publicSignals) {
      return false;
    }
    if (proof.a.length !== 2 || proof.b.length !== 2 || proof.c.length !== 2) {
      return false;
    }
    if (publicSignals.length < 2) {
      return false;
    }

    // Mock proofs are intentionally non-cryptographic, but they still reject
    // a public-signal mutation so the UI's tamper demonstration is honest.
    if (proof.publicSignals && JSON.stringify(proof.publicSignals) !== JSON.stringify(publicSignals)) {
      return false;
    }

    const score =
      this.publicSignalOrder === 'SCORE_FIRST'
        ? Number(publicSignals[0])
        : Number(publicSignals[1]);
    const version =
      this.publicSignalOrder === 'SCORE_FIRST'
        ? Number(publicSignals[1])
        : Number(publicSignals[0]);

    if (version !== CREDIT_MODEL_VERSION) {
      return false;
    }
    if (score < 300 || score > 1300) {
      return false;
    }

    return true;
  }
}

/**
 * Groth16ProofService
 * Genuine snarkjs Groth16 proof generator and verifier.
 * Requires genuine compiled circuit artifacts (.wasm and .zkey).
 */
export class Groth16ProofService implements ProofService {
  private circuitWasmPath: string;
  private circuitZkeyPath: string;
  private verificationKeyPath: string;
  private publicSignalOrder: 'SCORE_FIRST' | 'VERSION_FIRST';

  constructor(options: ProofServiceConfig) {
    this.circuitWasmPath = options.circuitWasmPath ?? '';
    this.circuitZkeyPath = options.circuitZkeyPath ?? '';
    this.verificationKeyPath = options.verificationKeyPath ?? '';
    this.publicSignalOrder = options.publicSignalOrder ?? 'SCORE_FIRST';
  }

  /**
   * Validates presence of necessary circuit artifacts on disk.
   */
  public checkArtifacts(): { ready: boolean; missingFiles: string[] } {
    const missing: string[] = [];
    if (!this.circuitWasmPath || !fs.existsSync(this.circuitWasmPath)) {
      missing.push(`WASM artifact not found at: ${this.circuitWasmPath}`);
    }
    if (!this.circuitZkeyPath || !fs.existsSync(this.circuitZkeyPath)) {
      missing.push(`Proving key (zkey) not found at: ${this.circuitZkeyPath}`);
    }
    return {
      ready: missing.length === 0,
      missingFiles: missing,
    };
  }

  async generateProof(inputs: CreditScoringInputs): Promise<ProofGenerationResult> {
    // 1. Calculate expected score to cross-validate
    const expected = calculateCreditScore(inputs);

    // 2. Validate artifact availability
    const artifactCheck = this.checkArtifacts();
    if (!artifactCheck.ready) {
      throw new Error(
        `Groth16 proof generation failed: Missing circuit artifacts.\n` +
          artifactCheck.missingFiles.join('\n') +
          `\nPlease configure CIRCUIT_WASM_PATH and CIRCUIT_ZKEY_PATH or set PROOF_MODE=mock.`
      );
    }

    // 3. Prepare witness inputs for Circom circuit
    const circuitInputs = {
      incomeIndex: inputs.incomeIndex,
      repaymentIndex: inputs.repaymentIndex,
      historyIndex: inputs.historyIndex,
    };

    // 4. Execute snarkjs fullProve
    const { proof, publicSignals } = await snarkjs.groth16.fullProve(
      circuitInputs,
      this.circuitWasmPath,
      this.circuitZkeyPath
    );

    if (!publicSignals || publicSignals.length < 2) {
      throw new Error('Circuit execution returned insufficient public signals');
    }

    const returnedScore =
      this.publicSignalOrder === 'SCORE_FIRST'
        ? Number(publicSignals[0])
        : Number(publicSignals[1]);
    const returnedVersion =
      this.publicSignalOrder === 'SCORE_FIRST'
        ? Number(publicSignals[1])
        : Number(publicSignals[0]);

    // 5. Cross-check against canonical computation
    if (returnedScore !== expected.score) {
      throw new Error(
        `Circuit proof validation mismatch: circuit output score ${returnedScore} does not match expected canonical score ${expected.score}`
      );
    }
    if (returnedVersion !== expected.modelVersion) {
      throw new Error(
        `Circuit proof validation mismatch: circuit model version ${returnedVersion} does not match expected version ${expected.modelVersion}`
      );
    }

    // 6. Format proof coordinates for Solidity Verifier
    const solidityProof = formatSnarkjsProofForSolidity(proof, publicSignals);

    return {
      proof: solidityProof,
      publicSignals,
      score: returnedScore,
      modelVersion: returnedVersion,
      isMock: false,
      generatedAt: new Date().toISOString(),
    };
  }

  async verifyProof(proof: SolidityProof, publicSignals: string[]): Promise<boolean> {
    if (!this.verificationKeyPath || !fs.existsSync(this.verificationKeyPath)) {
      throw new Error(
        `Verification key file not found at: ${this.verificationKeyPath}. Please configure VERIFICATION_KEY_PATH.`
      );
    }

    const vKeyRaw = fs.readFileSync(this.verificationKeyPath, 'utf8');
    const vKey = JSON.parse(vKeyRaw);

    // Reconstruct raw snarkjs proof format from Solidity coordinates
    const snarkProof = {
      pi_a: [proof.a[0], proof.a[1], '1'],
      pi_b: [
        [proof.b[0][1], proof.b[0][0]],
        [proof.b[1][1], proof.b[1][0]],
        ['1', '0'],
      ],
      pi_c: [proof.c[0], proof.c[1], '1'],
      protocol: 'groth16',
      curve: 'bn128',
    };

    return await snarkjs.groth16.verify(vKey, publicSignals, snarkProof);
  }
}

/**
 * Factory helper to instantiate the configured proof service.
 * In real mode we return the circuit-aware ZkCredit proof service so proofs
 * validate against the shipped Person 1 circuit + Person 2 VerityManager.
 */
export function createProofService(options: {
  proofMode: 'mock' | 'real';
  circuitWasmPath?: string;
  circuitZkeyPath?: string;
  verificationKeyPath?: string;
}): ProofService {
  if (options.proofMode === 'real') {
    return new ZkCreditProofService({
      circuitWasmPath: options.circuitWasmPath ?? '',
      circuitZkeyPath: options.circuitZkeyPath ?? '',
      verificationKeyPath: options.verificationKeyPath ?? '',
    } as any);
  }
  return new MockProofService();
}
